-- Receipt recipient projection: a third entity alongside the logical payment and its attempts.
-- A recipient is identified by the logical pair and the stazione_recipient discriminator; the
-- payment token travels in the receipt but does not identify the recipient.
-- changeset pagopa:0005-01-recipient
CREATE TABLE IF NOT EXISTS observability.recipient (
    id                  bigint      GENERATED BY DEFAULT AS IDENTITY,
    payment_id          bigint      NOT NULL,
    recipient_id        varchar(32) NOT NULL,
    stazione_recipient  varchar(64),
    first_seen_at       timestamp(6) NOT NULL,
    expires_at          timestamp(6),
    timeline_incomplete boolean     NOT NULL,
    current_state       varchar(32),
    position            integer,
    CONSTRAINT recipient_pk PRIMARY KEY (id),
    CONSTRAINT uk_recipient_id UNIQUE (recipient_id),
    CONSTRAINT fk_recipient_payment FOREIGN KEY (payment_id)
        REFERENCES observability.payment (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_recipient_payment ON observability.recipient (payment_id);
CREATE INDEX IF NOT EXISTS idx_recipient_station ON observability.recipient (stazione_recipient);
CREATE INDEX IF NOT EXISTS idx_recipient_state   ON observability.recipient (current_state);
CREATE INDEX IF NOT EXISTS idx_recipient_expires ON observability.recipient (expires_at);
-- rollback DROP TABLE IF EXISTS observability.recipient;

