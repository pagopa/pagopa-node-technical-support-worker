-- ======================================================================================
-- Primitive request/response aggregates (spec §3.3.2). RE interface events (REQ/RESP) are paired
-- by (session_id, tipo_evento) in a transient work table and only aggregated counts survive.
-- No payload and no payment key is stored; session_id lives only until the call is settled or
-- the pending TTL elapses.
-- ======================================================================================

-- changeset pagopa:0006-01-primitive-call
CREATE TABLE IF NOT EXISTS observability.primitive_call (
    id                 bigint       GENERATED BY DEFAULT AS IDENTITY,
    session_id         varchar(128) NOT NULL,
    tipo_evento        varchar(128) NOT NULL,
    request_at         timestamp(6),
    response_at        timestamp(6),
    service_identifier varchar(64)  NOT NULL,
    psp                varchar(64)  NOT NULL,
    canale             varchar(64)  NOT NULL,
    stazione           varchar(64)  NOT NULL,
    warned             boolean      NOT NULL,
    created_at         timestamp(6) NOT NULL,
    CONSTRAINT primitive_call_pk PRIMARY KEY (id),
    CONSTRAINT uk_primitive_call UNIQUE (session_id, tipo_evento)
);
CREATE INDEX IF NOT EXISTS idx_primitive_call_pending ON observability.primitive_call (warned, request_at);
CREATE INDEX IF NOT EXISTS idx_primitive_call_created ON observability.primitive_call (created_at);
-- rollback DROP TABLE IF EXISTS observability.primitive_call;

