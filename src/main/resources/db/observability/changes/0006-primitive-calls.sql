    psp                varchar(64)  NOT NULL,
    canale             varchar(64)  NOT NULL,
    stazione           varchar(64)  NOT NULL,
    requests           bigint       NOT NULL,
    responses          bigint       NOT NULL,
    warnings           bigint       NOT NULL,
    CONSTRAINT primitive_count_pk PRIMARY KEY (id),
    CONSTRAINT uk_primitive_count UNIQUE (bucket_start, service_identifier, primitive, psp, canale, stazione)
);
CREATE INDEX IF NOT EXISTS idx_primitive_count_bucket ON observability.primitive_count (bucket_start);
