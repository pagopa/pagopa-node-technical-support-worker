-- The `observability` schema is a prerequisite created by the DBA bootstrap script
-- (00-create-schema-and-user.sql); it is intentionally NOT created here. The app role
-- that runs this changelog holds CREATE on the schema but not on the database, so a
-- `CREATE SCHEMA` statement would fail with "permission denied for database" even with
-- IF NOT EXISTS (PostgreSQL checks the database privilege before the existence check).

-- changeset pagopa:0001-02-payment
CREATE TABLE IF NOT EXISTS observability.payment (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY,
    pa_fiscal_code      varchar(11) NOT NULL,
    notice_number       varchar(18) NOT NULL,
    projection_revision bigint      NOT NULL,
    timeline_incomplete boolean     NOT NULL,
    current_state       varchar(32) NOT NULL,
    CONSTRAINT payment_pk PRIMARY KEY (id),
    CONSTRAINT uk_payment_key UNIQUE (pa_fiscal_code, notice_number)
);
CREATE INDEX IF NOT EXISTS idx_payment_key   ON observability.payment (pa_fiscal_code, notice_number);
CREATE INDEX IF NOT EXISTS idx_payment_pa    ON observability.payment (pa_fiscal_code);
CREATE INDEX IF NOT EXISTS idx_payment_state ON observability.payment (current_state);
-- rollback DROP TABLE IF EXISTS observability.payment;

